export const GTBI_INTERPRETATION_SHORT =
  "GTBI (Global Trauma Burden Index) is a comparative, population-level index showing how heavily a country-year " +
  "is burdened by trauma-related exposures and consequences - armed conflict, communal violence, terrorism, " +
  "political repression, forced displacement, disaster-related trauma, and related public-health shocks - not a " +
  "clinical diagnosis or an exact PTSD-prevalence estimate. Higher values signal a stronger accumulated burden, " +
  "especially where several severe or persistent exposure channels coexist in the same country-year; lower values " +
  "suggest a lighter relative burden, not an absence of trauma or risk. Treat it as a normalized comparative scale - " +
  "focus on broad differences, trends over time, and clustering patterns rather than over-reading small gaps " +
  "between nearby scores, and don't sum the underlying per-exposure rows yourself; the GTBI field is the intended, " +
  "already-synthesized comparative signal.";

