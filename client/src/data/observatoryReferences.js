export const ETTI_INTERPRETATION_SHORT =
  "ETTI (Election Trauma Temperature Index) is a comparative measure of election-related trauma intensity - " +
  "the broader stress environment surrounding an election, not whether it was free and fair or how democratic " +
  "the country is more broadly. It combines four normalized (0-100) domains: EVS, TIE, PDL, and ITS. Higher " +
  "scores mean a heavier combined trauma burden across those domains in that election's coverage window; " +
  "lower scores mean relatively less cumulative trauma. Read scores comparatively, not as fixed thresholds - a " +
  "moderate ETTI score is not necessarily \"safe,\" it just indicates a lower combined burden than the " +
  "highest-scoring elections in this dataset. ETTI should not be used as a proxy for election integrity, " +
  "democratic quality, or regime type.";

